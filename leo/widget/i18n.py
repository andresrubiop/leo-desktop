def detect_language(setting: str = "auto") -> str:
    if setting in STRINGS:
        return setting
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value:
            return "es" if value.lower().startswith("es") else "en"
    return "en"


class Translator:
    def __init__(self, lang: str = "en"):
        self.lang = lang if lang in STRINGS else "en"

    def __call__(self, key: str, **kwargs) -> str:
        text = STRINGS[self.lang].get(key) or STRINGS["en"].get(key, key)
        return text.format(**kwargs) if kwargs else text

    def date(self, epoch: float) -> str:
        """Short local date: 'Nov 5' / '5 nov'."""
        t = time.localtime(epoch)
        return self("date", day=t.tm_mday, month=self("months").split()[t.tm_mon - 1])
