#!/usr/bin/env python3
"""Instalación solo de usuario, explícita, repetible y sin habilitar la extensión."""
import argparse
import json
import os
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parent.parent
UUID = "leo@local.desktop"
# PNG sprites derived locally from the user's photos (G7): installed on this computer only, never packaged.
SPRITES = ROOT / "assets/leo/generated/sprites"
APP = "io.github.leo.Companion"
MARKER = ".leo-managed"


def roots():
    data = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share"))
    config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    return data, config


def bin_dir():
    return Path(os.environ.get("XDG_BIN_HOME", Path.home() / ".local/bin"))


def quote_exec(path):
    # Desktop Exec and D-Bus Exec both accept quoted argv, not shell expansion.
    return '"' + str(path).replace('\\', '\\\\').replace('"', '\\"').replace('`', '\\`').replace('$', '\\$').replace('%', '%%') + '"'


def write_managed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink() or (path.exists() and "Generated by LEO installer" not in path.read_text()):
        raise RuntimeError(f"No se reemplazará un archivo ajeno: {path}")
    path.write_text(text)


def managed_dir(path):
    if path.is_symlink() or (path.exists() and not (path / MARKER).is_file()):
        raise RuntimeError(f"Ruta existente no administrada por LEO: {path}")
    path.mkdir(parents=True, exist_ok=True)
    (path / MARKER).write_text("Generated by LEO installer\n")


def install(autostart=False):
    import gi
    gi.require_version("Gtk", "4.0")
    data, config = roots()
    target = data / "leo/app"
    extension = data / "gnome-shell/extensions" / UUID
    # Preflight ownership before mutating either installation.
    for path in (target, extension):
        if path.is_symlink() or (path.exists() and not (path / MARKER).is_file()):
            raise RuntimeError(f"Ruta existente no administrada por LEO: {path}")
    for path in (target, extension):
        managed_dir(path)
    for folder in ("leo", "scripts"):
        shutil.copytree(ROOT / folder, target / folder, dirs_exist_ok=True, ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copytree(ROOT / "assets/leo", target / "assets/leo", dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("source-manifest.json", "*-preview.png", "portrait.png", "*-preview.gif",
                                                  "traits.json", "generated"))
    # Remove only the obsolete photo derived by earlier LEO installations.
    (target / "assets/leo/portrait.png").unlink(missing_ok=True)
    shutil.copytree(ROOT / "extension", extension, dirs_exist_ok=True)
    (extension / "assets").mkdir(exist_ok=True)
    # Sprites plus the third eye's forehead anchors (scripts/third_eye.py).
    for path in [*(ROOT / "assets/leo").glob("*.svg"), ROOT / "assets/leo/third-eye.json"]:
        shutil.copy2(path, extension / "assets" / path.name)
    generated = extension / "assets/generated"
    if generated.is_dir() and not generated.is_symlink():
        shutil.rmtree(generated)
    sprites = sorted(SPRITES.glob("*.png")) if SPRITES.is_dir() else []
    if sprites:
        generated.mkdir()
        for path in sprites:
            shutil.copy2(path, generated / path.name)
    # A wrapper avoids shell expansion and gives a stable Python module path.
    launcher = target / "launch.py"
    launcher.write_text('import sys\nfrom pathlib import Path\nsys.path.insert(0, str(Path(__file__).parent))\n'
                        'if sys.argv[1:] == ["daemon"]:\n    from leo.daemon import main\n'
                        'elif sys.argv[1:2] == ["ctl"]:\n    del sys.argv[1]\n    from leo.cli import main\n'
                        'else:\n    from leo.ui import main\nmain()\n')
    launch = f"/usr/bin/python3 {quote_exec(launcher)}"
    desktop = ("# Generated by LEO installer\n[Desktop Entry]\nType=Application\nName=LEO\n"
               "Comment=Tu compañero local\n" + f"Exec={launch}\nIcon={target / 'assets/leo/sit.svg'}\nTerminal=false\nCategories=Utility;\n"
               "Actions=usage;mail;chat;\n")
    for page, title in (("usage", "Uso de IA y cuentas"), ("mail", "Correo"), ("chat", "Conversar con Leo")):
        desktop += f"\n[Desktop Action {page}]\nName={title}\nExec={launch} --page {page}\n"
    write_managed(data / "applications" / f"{APP}.desktop", desktop)
    write_managed(data / "dbus-1/services" / f"{APP}.service",
                  f"# Generated by LEO installer\n[D-BUS Service]\nName={APP}\nExec={launch} daemon\n")
    # `leoctl notify` for scripts such as: python train.py; leoctl notify --event done --title train
    write_managed(bin_dir() / "leoctl",
                  f"#!/usr/bin/python3\n# Generated by LEO installer\nimport runpy, sys\n"
                  f"sys.argv.insert(1, 'ctl')\nrunpy.run_path({str(launcher)!r}, run_name='__main__')\n")
    (bin_dir() / "leoctl").chmod(0o755)
    auto = config / "autostart" / f"{APP}.desktop"
    if autostart:
        write_managed(auto, desktop.replace(f"Exec={launch}\n", f"Exec={launch} daemon\n"))
    print(f"Instalado: {target}\nExtensión: {extension}\nAutoarranque: {'habilitado' if auto.exists() else 'desactivado'}")
    print(f"Activa la extensión manualmente: gnome-extensions enable {UUID}")
    print("Una extensión nueva puede requerir cerrar y volver a iniciar sesión en Wayland.")


def uninstall():
    data, config = roots()
    # Refuse while enabled: caller must disable deliberately; never change GNOME silently.
    from gi.repository import Gio
    settings = Gio.Settings.new("org.gnome.shell")
    if UUID in settings.get_strv("enabled-extensions"):
        raise RuntimeError(f"Primero desactiva la extensión: gnome-extensions disable {UUID}")
    for path in (data / "applications" / f"{APP}.desktop", data / "dbus-1/services" / f"{APP}.service",
                 config / "autostart" / f"{APP}.desktop", bin_dir() / "leoctl"):
        if path.is_file() and not path.is_symlink() and "Generated by LEO installer" in path.read_text():
            path.unlink()
    for path in (data / "leo/app", data / "gnome-shell/extensions" / UUID):
        if not path.is_symlink() and (path / MARKER).is_file():
            shutil.rmtree(path)
    print("Aplicación y extensión retiradas. Se conservan configuración, notas y todas las fotos originales.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--autostart", action="store_true", help="Habilitar daemon al iniciar sesión; por defecto no")
    parser.add_argument("--disable-autostart", action="store_true")
    args = parser.parse_args()
    if args.disable_autostart:
        path = roots()[1] / "autostart" / f"{APP}.desktop"
        if path.is_file() and not path.is_symlink() and "Generated by LEO installer" in path.read_text():
            path.unlink()
        print("Autoarranque de LEO desactivado")
    elif args.uninstall:
        uninstall()
    else:
        install(args.autostart)


if __name__ == "__main__":
    main()
