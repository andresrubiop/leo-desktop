import importlib.util
import os
import sys
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

spec = importlib.util.spec_from_file_location("leo_installer", Path(__file__).resolve().parents[1] / "scripts/install.py")
installer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(installer)


class InstallerTests(unittest.TestCase):
    def test_install_is_repeatable_and_uninstall_preserves_notes(self):
        with tempfile.TemporaryDirectory(prefix="leo-install-") as directory:
            root = Path(directory)
            with patch.dict(os.environ, XDG_DATA_HOME=str(root / "data"), XDG_CONFIG_HOME=str(root / "config"),
                            XDG_BIN_HOME=str(root / "bin")):
                sprites = root / "sprites"
                sprites.mkdir()
                (sprites / "sit.png").write_bytes(b"\x89PNG local")
                with patch.object(installer, "SPRITES", sprites):
                    installer.install()
                local = root / "data/gnome-shell/extensions/leo@local.desktop/assets/generated/sit.png"
                self.assertEqual(local.read_bytes(), b"\x89PNG local")
                installer.install()  # Without local sprites the previous copies are removed.
                self.assertFalse(local.parent.exists())
                leoctl = root / "bin/leoctl"
                self.assertTrue(os.access(leoctl, os.X_OK))
                import subprocess
                usage = subprocess.run([sys.executable, str(leoctl), "notify", "--help"], capture_output=True, text=True, timeout=30)
                self.assertEqual(usage.returncode, 0, usage.stderr)
                self.assertIn("--event", usage.stdout)
                old_portrait = root / "data/leo/app/assets/leo/portrait.png"
                old_portrait.write_bytes(b"obsolete derived photo")
                installer.install()
                self.assertFalse(old_portrait.exists())
                self.assertTrue((root / "data/gnome-shell/extensions/leo@local.desktop/assets/walk-23.svg").is_file())
                self.assertTrue((root / "data/gnome-shell/extensions/leo@local.desktop/movement.js").is_file())
                self.assertTrue((root / "data/leo/app/leo/ui.py").is_file())
                self.assertTrue((root / "data/gnome-shell/extensions/leo@local.desktop/assets/sit.svg").is_file())
                from gi.repository import Gio
                launcher = Gio.DesktopAppInfo.new_from_filename(str(root / "data/applications/io.github.leo.Companion.desktop"))
                self.assertEqual(launcher.get_icon().get_file().get_path(), str(root / "data/leo/app/assets/leo/sit.svg"))
                self.assertFalse((root / "config/autostart/io.github.leo.Companion.desktop").exists())
                installer.install(autostart=True)
                self.assertTrue((root / "config/autostart/io.github.leo.Companion.desktop").is_file())
                notes = root / "data/leo/notes"
                notes.mkdir()
                (notes / "keep.md").write_text("keep")
                with patch.object(Gio.Settings, "new") as settings:
                    settings.return_value.get_strv.return_value = []
                    installer.uninstall()
                    installer.uninstall()
                self.assertFalse((root / "data/leo/app").exists())
                self.assertFalse(leoctl.exists())
                self.assertEqual((notes / "keep.md").read_text(), "keep")

    def test_refuse_unmanaged_installation_and_symlink(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            with patch.dict(os.environ, XDG_DATA_HOME=str(root / "data"), XDG_CONFIG_HOME=str(root / "config"),
                            XDG_BIN_HOME=str(root / "bin")):
                unmanaged = root / "data/leo/app"
                unmanaged.mkdir(parents=True)
                with self.assertRaises(RuntimeError): installer.install()
                original = root / "original"
                original.write_text("# Generated by LEO installer\nKeep")
                link = root / "link"
                link.symlink_to(original)
                with self.assertRaises(RuntimeError): installer.write_managed(link, "overwrite")
                self.assertIn("Keep", original.read_text())


if __name__ == "__main__":
    unittest.main()
